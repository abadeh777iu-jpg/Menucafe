// Generates migrations/0002_seed.sql from ../data/*.json (the demo restaurants) and the default
// theme rules. Run after changing the JSON files: `npm run build:seed`.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cleanIcon, cleanSlug, cleanTheme } from '../src/store.js';
import { DEFAULT_RULES, TIMEZONE_NAME } from '../src/schedule.js';
import { insert } from './sql.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = join(here, '..', '..', 'data');
const out = join(here, '..', 'migrations', '0002_seed.sql');

const stamp = 1700000000; // fixed, so regenerating the file produces identical output
const lines = ['-- Generated by scripts/build-seed.mjs from data/*.json. Do not edit by hand.'];
const files = (await readdir(dataDir)).filter((name) => name.endsWith('.json')).sort();

for (const file of files) {
  const data = JSON.parse(await readFile(join(dataDir, file), 'utf8'));
  const info = data.restaurant;
  const slug = cleanSlug(info.slug);
  const theme = cleanTheme(info.theme || 'default');
  lines.push(insert('restaurants', {
    slug, name: info.name, english_name: info.englishName || '', mark: info.mark || '',
    headline: info.headline || '', note: info.note || '', description: info.description || '',
    footer: info.footer || '', theme, created_at: stamp, updated_at: stamp,
  }));
  data.categories.forEach((category, position) => {
    lines.push(insert('categories', {
      restaurant_slug: slug, id: category.id, name: category.name,
      icon: cleanIcon(category.icon), position, enabled: 1,
    }));
  });
  data.items.forEach((item, position) => {
    lines.push(insert('items', {
      restaurant_slug: slug, category_id: item.category, name: item.name,
      description: item.description || '', ingredients: item.ingredients || '',
      allergens: JSON.stringify(item.allergens || []), price: Number(item.price),
      icon: cleanIcon(item.icon), label: item.label || null, visible: 1, position,
    }));
  });
  DEFAULT_RULES.forEach((rule, position) => {
    lines.push(insert('theme_rules', {
      restaurant_slug: slug, key: rule.key, kind: rule.kind, label: rule.label, theme: rule.theme,
      enabled: 1, calendar: rule.calendar, start_month: rule.start[0], start_day: rule.start[1],
      end_month: rule.end[0], end_day: rule.end[1], priority: rule.priority,
      timezone: TIMEZONE_NAME, position, updated_at: stamp,
    }));
  });
}

await writeFile(out, lines.join('\n') + '\n', 'utf8');
console.log(`wrote ${out} (${files.length} restaurants)`);
